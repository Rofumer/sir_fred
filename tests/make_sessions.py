"""Generate deterministic key scripts (tests/sessions/*.txt) by driving the
original game with simple navigation logic. A script line is
'<frames> [KEY ...]' and replays identically in every harness."""
import os

from common import ORIGINAL, FRED_X, FRED_Y, ROPE_ON, Emu, HERE


class Recorder:
    def __init__(self, e):
        self.e = e
        self.lines = []
        self.keys = ()

    def frames(self, n, *keys):
        e = self.e
        e.release()
        e.press(*keys)
        for _ in range(n):
            e.run_frames(1)
        if self.lines and self.lines[-1][1] == keys:
            self.lines[-1][0] += n
        else:
            self.lines.append([n, keys])

    def until(self, cond, keys, limit):
        n = 0
        while n < limit and not cond():
            self.frames(1, *keys)
            n += 1

    def walk_to(self, target):
        for _ in range(200):
            x = self.e.peek(FRED_X)
            if abs(x - target) <= 1:
                return
            self.frames(1, 'P' if target > x else 'O')
            self.frames(14)

    def save(self, name):
        with open(os.path.join(HERE, 'sessions', name), 'w') as f:
            f.write('# generated by tests/make_sessions.py\n')
            for n, k in self.lines:
                f.write('%d %s\n' % (n, ' '.join(k)))


def explore2(path=ORIGINAL, save=True, log=None):
    e = Emu(path)
    r = Recorder(e)
    r.frames(10)
    r.frames(5, '0')
    r.frames(150)
    r.frames(160, 'P')                 # run, grab rope, fall into the pit
    r.frames(60)
    r.walk_to(126)
    r.walk_to(138)                     # under the vine, facing right
    r.until(lambda: e.peek(ROPE_ON), ('Q',), 40)
    r.until(lambda: not e.peek(ROPE_ON) and e.peek(FRED_Y) < 80, ('Q',), 300)
    r.frames(60)
    r.until(lambda: e.peek(FRED_X) < 20, ('P',), 400)   # up the hill, room 3
    r.frames(30)
    r.frames(60, 'P')                  # into the water
    r.frames(80)
    for k in ('P', 'A', 'P', 'Q', 'O', 'A', 'P', 'Q', 'Q', 'P'):
        r.frames(40, k)
    r.frames(60, 'Z')
    r.frames(60, 'M')
    r.frames(100)
    if save:
        r.save('explore2.txt')
        e.screenshot(os.path.join(HERE, '..', 'build', 'explore2_end.png'))
    return e


if __name__ == '__main__':
    e = explore2()
    print('explore2 end', e.peek(FRED_X), e.peek(FRED_Y), 'frames', e.frame)
